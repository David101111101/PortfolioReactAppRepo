async function logConversation(
  env: Env,
  question: string,
  reason: string,
  answer: string,
  answer_confidence: number
) {
  try {
      // log start time to measure logging latency, which can help identify if logging is causing performance issues in the request handling
      requestStart = Date.now();
      const response = await fetch(`${env.SUPABASE_URL}/rest/v1/abuse_logs`, {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        apikey: env.SUPABASE_SERVICE_ROLE_KEY,
        Authorization: `Bearer ${env.SUPABASE_SERVICE_ROLE_KEY}`,
        Prefer: "return=minimal",
      },
      body: JSON.stringify({
        question,
        reason,
        answer,
        answer_confidence,
      }),
    });
      if (!response.ok) {
    const text = await response.text();
    throw new Error(`Supabase insert failed: ${response.status} ${text}`);
  }
  } catch (err) {
    console.error("Logging into DB failed:", err);
  }
}
function streamText(text: string) { // Utility function to create a ReadableStream from a string, used for streaming responses back to the client, allowing for partial answers to be sent as they are generated by the LLM, improving perceived responsiveness and user experience.
  return new ReadableStream({
    async start(controller) {
      const encoder = new TextEncoder();

      for (const char of text) {
        controller.enqueue(encoder.encode(char));
        await new Promise((r) => setTimeout(r, 40));
      }
      controller.close();
    },
  });
}
